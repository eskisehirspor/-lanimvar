"""Generate the İLANIM VAR wordmark as outline paths.

Set once from the display fonts, shaped with HarfBuzz (real kerning), written
to src/brand/generated/wordmarkPaths.ts. The İ's dot is NOT the font's: the
dotless capital I is set and the brand dot is drawn over its stem, so it can
carry the brand colour and animate independently.

    pip install fonttools uharfbuzz && python3 scripts/brand/generate-wordmark.py
"""
import json
import pathlib

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parents[2]
FONTS = ROOT / "node_modules" / "@expo-google-fonts"
TEXT = "ILANIM VAR"
DIRECTIONS = {
    "condensed": FONTS / "barlow-condensed/800ExtraBold/BarlowCondensed_800ExtraBold.ttf",
    "standard": FONTS / "bricolage-grotesque/800ExtraBold/BricolageGrotesque_800ExtraBold.ttf",
}
TRACKING = {"condensed": 10, "standard": -18}  # font units per glyph, optical tightening


def build(key: str, font_path: pathlib.Path) -> dict:
    face = hb.Face(hb.Blob.from_file_path(str(font_path)))
    font = hb.Font(face)
    buf = hb.Buffer()
    buf.add_str(TEXT)
    buf.guess_segment_properties()
    buf.language = "tr"
    hb.shape(font, buf, {"kern": True, "liga": False})

    tt = TTFont(str(font_path))
    glyph_set = tt.getGlyphSet()
    order = tt.getGlyphOrder()
    cap = tt["OS/2"].sCapHeight
    pen = SVGPathPen(glyph_set)
    x = 0
    first = None
    for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
        glyph = glyph_set[order[info.codepoint]]
        glyph.draw(TransformPen(pen, (1, 0, 0, -1, x + pos.x_offset, cap)))
        if first is None:
            bp = BoundsPen(glyph_set)
            glyph.draw(bp)
            first = (x + bp.bounds[0], x + bp.bounds[2])
        x += pos.x_advance + TRACKING[key]
    stem = first[1] - first[0]
    return {
        "path": pen.getCommands(),
        "advance": x - TRACKING[key],
        "capHeight": cap,
        "dot": {"cx": round(first[0] + stem / 2, 1), "r": round(stem * 0.6, 1), "gap": round(stem * 0.3, 1)},
    }


data = {k: build(k, p) for k, p in DIRECTIONS.items()}
out = ROOT / "src/brand/generated/wordmarkPaths.ts"
out.write_text(
    "// GENERATED by scripts/brand/generate-wordmark.py. Do not edit by hand.\n"
    "// Font units (1000/em). Cap-height top is y=0, baseline is y=capHeight.\n\n"
    f"export const wordmarkPaths = {json.dumps(data, indent=2)} as const;\n"
)
print({k: (v["advance"], v["dot"]) for k, v in data.items()})
